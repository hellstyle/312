# Keepalive HTTP-сервер для хостингов типа Render, которые засыпают если нет
# входящих запросов. Слушает PORT из env (Render проставляет его автоматически).
# На локальной машине просто висит на 8080 и никому не мешает.
# ---------------------------------------------------------------------------
def _start_keepalive_server():
    class _Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            self.send_response(200)
            self.end_headers()
            self.wfile.write(b"FunPayCardinal is running")
        def do_HEAD(self):
            self.send_response(200)
            self.end_headers()
        def log_message(self, fmt, *args):
            pass  # не спамить в логи от каждого ping-запроса

    port = int(os.environ.get("PORT", 8080))
    try:
        server = http.server.HTTPServer(("", port), _Handler)
        server.serve_forever()
    except Exception:
        pass  # если порт занят — просто не запускаем, бот продолжает работу

threading.Thread(target=_start_keepalive_server, daemon=True).start()
